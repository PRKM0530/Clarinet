"""
clarinet/models/traffic.py
M1-owned traffic and collector tables.

Tables:
  TrafficSample      — raw per-device per-poll byte counters
  UsageActivity      — classified activity buckets (extended columns)
  UsageDaily         — pre-rolled daily totals
  DomainObservation  — DNS/SNI domain touch (no payload stored)
  CollectorHeartbeat — last-alive timestamp for each collector thread
"""

from datetime import datetime

from sqlalchemy import DateTime, Float, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from clarinet.database import Base


class TrafficSample(Base):
    """
    Raw per-device byte counters from each poll cycle.
    Stored for delta computation; purged after 24 h.
    """
    __tablename__ = "traffic_sample"

    sample_id: Mapped[int] = mapped_column(Integer, primary_key=True)
    device_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("device.device_id", ondelete="CASCADE"), index=True
    )
    sampled_at: Mapped[datetime] = mapped_column(DateTime, nullable=False, index=True)
    bytes_in: Mapped[int] = mapped_column(Integer, default=0)
    bytes_out: Mapped[int] = mapped_column(Integer, default=0)
    # Source: "nft" | "packet" | "null"
    source: Mapped[str] = mapped_column(String(16), default="nft")

    device: Mapped["Device"] = relationship("Device")  # type: ignore[name-defined]


class UsageActivity(Base):
    """
    Per-device per-hour classified traffic (extended from UsageRecord).
    M1 writes to the core UsageRecord for compatibility;
    this table stores the richer classification breakdown.
    """
    __tablename__ = "usage_activity"

    activity_id: Mapped[int] = mapped_column(Integer, primary_key=True)
    device_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("device.device_id", ondelete="CASCADE"), index=True
    )
    date: Mapped[str] = mapped_column(String(10), nullable=False, index=True)  # "YYYY-MM-DD"
    hour: Mapped[int] = mapped_column(Integer, nullable=False)                 # 0-23
    # STREAMING | GAMING | BROWSING | VOIP | DOWNLOAD | UPLOAD | OTHER
    category: Mapped[str] = mapped_column(String(16), default="OTHER")
    bytes_in: Mapped[int] = mapped_column(Integer, default=0)
    bytes_out: Mapped[int] = mapped_column(Integer, default=0)


class UsageDaily(Base):
    """
    Pre-rolled daily totals per device. Generated by the aggregate job.
    """
    __tablename__ = "usage_daily"

    daily_id: Mapped[int] = mapped_column(Integer, primary_key=True)
    device_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("device.device_id", ondelete="CASCADE"), index=True
    )
    date: Mapped[str] = mapped_column(String(10), nullable=False, index=True)
    bytes_in: Mapped[int] = mapped_column(Integer, default=0)
    bytes_out: Mapped[int] = mapped_column(Integer, default=0)
    peak_hour: Mapped[int | None] = mapped_column(Integer, nullable=True)  # hour with most traffic


class DomainObservation(Base):
    """
    DNS / SNI domain observations (privacy-safe: no payload, no full URLs).
    Used for category classification and usage breakdown.
    """
    __tablename__ = "domain_observation"

    obs_id: Mapped[int] = mapped_column(Integer, primary_key=True)
    device_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("device.device_id", ondelete="CASCADE"), index=True
    )
    # Bare domain (e.g. "youtube.com") — TLD+1 only, never subdomain payloads
    domain: Mapped[str] = mapped_column(String(253), nullable=False, index=True)
    category: Mapped[str] = mapped_column(String(32), default="UNKNOWN")
    observed_at: Mapped[datetime] = mapped_column(DateTime, nullable=False, index=True)
    # How many DNS queries in this minute
    hit_count: Mapped[int] = mapped_column(Integer, default=1)


class CollectorHeartbeat(Base):
    """
    Watchdog table — each collector thread writes a heartbeat every cycle.
    Alerts if a collector goes silent for > 2× its expected interval.
    """
    __tablename__ = "collector_heartbeat"

    heartbeat_id: Mapped[int] = mapped_column(Integer, primary_key=True)
    # Collector name: "arp_scanner" | "traffic_counter" | "dns_sniffer" | "pinger"
    collector: Mapped[str] = mapped_column(String(32), unique=True, nullable=False)
    last_seen: Mapped[datetime] = mapped_column(DateTime, nullable=False)
    # Expected interval so watchdog can compute lag
    interval_s: Mapped[int] = mapped_column(Integer, default=60)
    ok: Mapped[bool] = mapped_column(Integer, default=True)  # reuse Integer for SQLite compat
